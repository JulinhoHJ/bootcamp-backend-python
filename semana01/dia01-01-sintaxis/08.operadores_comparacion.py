x, y = 20, 15
print('x:', 20, 'y:', y)

respuesta = x > y # -> True
print("¿x es mayor que y? ", respuesta, type(respuesta))
print("¿x es mayor o igual que y? ", x >= y, type(x >= y))
print("¿x es menor que y? ", x < y, type(x < y))
print("¿x es menor o igual que y? ", x <= y, type(x <= y))
print("¿x es igual que y? ", x == y, type(x == y))
print("¿x es distinto de y? ", x != y, type(x != y))