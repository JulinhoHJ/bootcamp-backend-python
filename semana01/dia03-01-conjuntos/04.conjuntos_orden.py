colorSet = {'red', 'green', 'blue', 'yellow', 'blue', 'red'}

# Ordenar un lista/conjunto
ordenada = sorted(colorSet)
print(ordenada)

# Invertir un lista/conjunto
colorList = list(colorSet) # Convertir a lista
print('colorList: ', colorList)
listaInversa = list(reversed(colorList))
print('listaInversa: ', listaInversa)